# 趋势选股
import pandas as pd
import numpy as np
# ============================================================
# 配置
# ============================================================

INPUT_FILE = "tickflow_3_day.csv"
OUTPUT_FILE = "trend_result.csv"

# 至少需要60个交易日
MIN_DAYS = 60


# ============================================================
# 读取数据
# ============================================================

print("========================================")
print("趋势策略开始运行")
print("========================================")

print(f"读取数据：{INPUT_FILE}")

df = pd.read_csv(
    INPUT_FILE,
    encoding="utf-8-sig"
)


# ============================================================
# 基础处理
# ============================================================

df["trade_date"] = pd.to_datetime(
    df["trade_date"]
)

df = df.sort_values(
    by=["symbol", "trade_date"]
).reset_index(drop=True)


# 删除 ST、退市
df = df[
    ~df["name"].str.contains(
        "ST|退",
        na=False
    )
].copy()


# 删除关键数据为空
df = df.dropna(
    subset=[
        "close",
        "high",
        "low",
        "pct_change"
    ]
)


# ============================================================
# 保存结果
# ============================================================

result_list = []


# ============================================================
# 每只股票单独计算
# ============================================================

for symbol, group in df.groupby("symbol"):

    g = group.sort_values(
        "trade_date"
    ).reset_index(drop=True)


    # --------------------------------------------------------
    # 数据不足60个交易日
    # --------------------------------------------------------

    if len(g) < MIN_DAYS:
        continue


    # --------------------------------------------------------
    # 均线
    # --------------------------------------------------------

    g["MA5"] = (
        g["close"]
        .rolling(5)
        .mean()
    )

    g["MA20"] = (
        g["close"]
        .rolling(20)
        .mean()
    )

    g["MA60"] = (
        g["close"]
        .rolling(60)
        .mean()
    )


    # --------------------------------------------------------
    # MA20方向
    #
    # 当前MA20 与 5个交易日前MA20比较
    # --------------------------------------------------------

    g["MA20_5D_AGO"] = (
        g["MA20"].shift(5)
    )


    # --------------------------------------------------------
    # 最近20日最高价
    # 不包含今天
    # --------------------------------------------------------

    g["HIGH_20"] = (
        g["high"]
        .rolling(20)
        .max()
        .shift(1)
    )


    # --------------------------------------------------------
    # 最近20日最低价
    # 不包含今天
    # --------------------------------------------------------

    g["LOW_20"] = (
        g["low"]
        .rolling(20)
        .min()
        .shift(1)
    )


    # --------------------------------------------------------
    # 最近20日价格位置
    #
    # 0   = 接近20日最低
    # 100 = 接近20日最高
    # --------------------------------------------------------

    price_range = (
        g["HIGH_20"] -
        g["LOW_20"]
    )

    g["POSITION_20"] = np.where(
        price_range > 0,
        (
            (
                g["close"] -
                g["LOW_20"]
            ) /
            price_range
        ) * 100,
        np.nan
    )


    # --------------------------------------------------------
    # 最近5日涨跌幅
    # --------------------------------------------------------

    g["CHANGE_5D"] = (
        (
            g["close"] /
            g["close"].shift(5)
            - 1
        ) * 100
    )


    # --------------------------------------------------------
    # 最近10日涨跌幅
    # --------------------------------------------------------

    g["CHANGE_10D"] = (
        (
            g["close"] /
            g["close"].shift(10)
            - 1
        ) * 100
    )


    # --------------------------------------------------------
    # 最近20日涨跌幅
    # --------------------------------------------------------

    g["CHANGE_20D"] = (
        (
            g["close"] /
            g["close"].shift(20)
            - 1
        ) * 100
    )


    # --------------------------------------------------------
    # 最近5日平均涨跌幅
    # --------------------------------------------------------

    g["AVG_PCT_5D"] = (
        g["pct_change"]
        .rolling(5)
        .mean()
    )


    # --------------------------------------------------------
    # 最新一天
    # --------------------------------------------------------

    latest = g.iloc[-1]


    # 如果指标还没有准备好
    if pd.isna(latest["MA60"]):
        continue

    if pd.isna(latest["MA20_5D_AGO"]):
        continue

    if pd.isna(latest["POSITION_20"]):
        continue


    # ========================================================
    # 趋势评分
    # ========================================================

    score = 0

    reasons = []


    # --------------------------------------------------------
    # 1. MA5 > MA20
    # --------------------------------------------------------

    if latest["MA5"] > latest["MA20"]:

        score += 15

        reasons.append(
            "MA5>MA20"
        )


    # --------------------------------------------------------
    # 2. MA20 > MA60
    # --------------------------------------------------------

    if latest["MA20"] > latest["MA60"]:

        score += 15

        reasons.append(
            "MA20>MA60"
        )


    # --------------------------------------------------------
    # 3. MA20向上
    # --------------------------------------------------------

    if (
        latest["MA20"] >
        latest["MA20_5D_AGO"]
    ):

        score += 20

        reasons.append(
            "MA20向上"
        )


    # --------------------------------------------------------
    # 4. 当前价格 > MA20
    # --------------------------------------------------------

    if latest["close"] > latest["MA20"]:

        score += 15

        reasons.append(
            "价格>MA20"
        )


    # --------------------------------------------------------
    # 5. 当前价格位于20日区间高位
    # --------------------------------------------------------

    position = latest["POSITION_20"]


    if position >= 80:

        score += 20

        reasons.append(
            "20日区间高位"
        )

    elif position >= 65:

        score += 12

        reasons.append(
            "20日区间偏强"
        )

    elif position >= 50:

        score += 5

        reasons.append(
            "20日区间中上部"
        )


    # --------------------------------------------------------
    # 6. 最近5日上涨
    # --------------------------------------------------------

    if latest["CHANGE_5D"] > 0:

        score += 5

        reasons.append(
            "5日上涨"
        )


    # --------------------------------------------------------
    # 7. 最近10日上涨
    # --------------------------------------------------------

    if latest["CHANGE_10D"] > 0:

        score += 5

        reasons.append(
            "10日上涨"
        )


    # --------------------------------------------------------
    # 限制最高100分
    # --------------------------------------------------------

    score = min(
        score,
        100
    )


    # ========================================================
    # 趋势分类
    # ========================================================

    if score >= 85:

        trend = "强趋势"

    elif score >= 70:

        trend = "上升趋势"

    elif score >= 55:

        trend = "偏强"

    elif score >= 40:

        trend = "震荡"

    else:

        trend = "弱趋势"


    # ========================================================
    # 添加最新结果
    # ========================================================

    result_list.append({

        "symbol": latest["symbol"],

        "name": latest["name"],

        "trade_date": latest["trade_date"],

        "close": latest["close"],

        "pct_change": latest["pct_change"],

        "MA5": latest["MA5"],

        "MA20": latest["MA20"],

        "MA60": latest["MA60"],

        "CHANGE_5D": latest["CHANGE_5D"],

        "CHANGE_10D": latest["CHANGE_10D"],

        "CHANGE_20D": latest["CHANGE_20D"],

        "POSITION_20": latest["POSITION_20"],

        "trend_score": score,

        "trend": trend,

        "reason": ";".join(reasons)

    })


# ============================================================
# 没有结果
# ============================================================

if not result_list:

    print()
    print("没有足够的数据计算趋势。")
    print(
        "请确认 tickflow_3_day.csv "
        "至少包含60个交易日数据。"
    )

    exit()


# ============================================================
# 合并
# ============================================================

result = pd.DataFrame(
    result_list
)


# ============================================================
# 结果筛选
# ============================================================

# 1. 剔除当前股价 > 30 元的股票
result = result[
    result["close"] <= 30
].copy()


# ============================================================
# 2. 按趋势评分从高到低排序
# ============================================================

result = result.sort_values(
    by=[
        "trend_score",
        "CHANGE_5D"
    ],
    ascending=[
        False,
        False
    ]
).reset_index(drop=True)


# ============================================================
# 3. 保存全部符合价格条件的结果
# ============================================================

result.to_csv(
    OUTPUT_FILE,
    index=False,
    encoding="utf-8-sig"
)


# ============================================================
# 4. 取评分最高的30只
# ============================================================

top30 = result.head(30).copy()


# ============================================================
# 5. 保存TOP30
# ============================================================

TOP30_FILE = "trend_top30.csv"

top30.to_csv(
    TOP30_FILE,
    index=False,
    encoding="utf-8-sig"
)


# ============================================================
# 输出统计
# ============================================================

print()
print("========================================")
print("趋势策略执行完成")
print("========================================")

print(
    f"最新交易日："
    f"{result['trade_date'].max().strftime('%Y-%m-%d')}"
)

print(
    f"股价 ≤ 30 元股票：{len(result)}"
)

print(
    f"TOP30：{len(top30)}"
)


print()
print("趋势分类：")

print(
    result["trend"].value_counts()
)


print()
print("========================================")
print("趋势评分 TOP30")
print("========================================")

print(
    top30[
        [
            "symbol",
            "name",
            "close",
            "trend_score",
            "trend",
            "CHANGE_5D",
            "CHANGE_10D",
            "CHANGE_20D",
            "POSITION_20"
        ]
    ].to_string(
        index=False
    )
)


print()
print(
    f"全部结果：{OUTPUT_FILE}"
)

print(
    f"TOP30结果：{TOP30_FILE}"
)

print("========================================")